import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '../../..');
const check = process.argv.includes('--check');
let drift = false;

function readJson(path) {
	return JSON.parse(readFileSync(resolve(root, path), 'utf8'));
}

function write(path, content) {
	const target = resolve(root, path);
	if (check) {
		const current = readFileSync(target, 'utf8');
		if (current !== content) {
			console.error(`Generated contract is out of date: ${path}`);
			drift = true;
		}
		return;
	}
	mkdirSync(dirname(target), { recursive: true });
	writeFileSync(target, content);
}

function tsStringList(values) {
	return values.map((value) => `\t'${value}'`).join(',\n');
}

function goStringList(values) {
	return values.map((value) => `\t${JSON.stringify(value)},`).join('\n');
}

function gofmt(content) {
	return execFileSync('gofmt', { input: content, encoding: 'utf8' });
}

function goIdentifier(value, prefix = '') {
	const special = {
		api: 'API',
		auth: 'Auth',
		audit: 'Audit',
		dashboard: 'Dashboard',
		id: 'ID',
		ip: 'IP',
		jwks: 'JWKS',
		logs: 'Logs',
		smtp: 'SMTP',
		settings: 'Settings',
		ssl: 'SSL',
		tls: 'TLS',
		ui: 'UI'
	};
	return (
		prefix +
		value
			.split(/[^a-zA-Z0-9]+/)
			.filter(Boolean)
			.map((part) => special[part.toLowerCase()] ?? part.charAt(0).toUpperCase() + part.slice(1))
			.join('')
	);
}

function generateAdminAccessTs(contract) {
	const rolePermissions = JSON.stringify(contract.rolePermissions, null, '\t');
	return `// Code generated by packages/config/scripts/generate-contracts.mjs; DO NOT EDIT.
import contract from './admin-access.json';

export const roles = contract.roles as unknown as readonly [
${tsStringList(contract.roles)}
];
export const adminRoles = contract.adminRoles as unknown as readonly [
${tsStringList(contract.adminRoles)}
];
export const adminPermissions = contract.permissions as unknown as readonly [
${tsStringList(contract.permissions)}
];

export type Role = (typeof roles)[number];
export type AdminRole = (typeof adminRoles)[number];
export type AdminPermission = (typeof adminPermissions)[number];

export const rolePermissions = ${rolePermissions} as const satisfies Record<AdminRole, readonly AdminPermission[]>;

export function isRole(value: string): value is Role {
\treturn (roles as readonly string[]).includes(value);
}

export function isAdminRole(value: string): value is AdminRole {
\treturn (adminRoles as readonly string[]).includes(value);
}

export function isAdminPermission(value: string): value is AdminPermission {
\treturn (adminPermissions as readonly string[]).includes(value);
}
`;
}

function generateProductsTs(products) {
	return `// Code generated by packages/config/scripts/generate-contracts.mjs; DO NOT EDIT.
import catalog from './products.json';

export const products = catalog as unknown as readonly [
${products
	.map(
		(product) => `\t{
\t\tid: '${product.id}';
\t\tname: '${product.name}';
\t\tappUrl: '${product.appUrl}';
\t\tdescriptionKey: '${product.descriptionKey}';
\t}`
	)
	.join(',\n')}
];

export type ProductId = (typeof products)[number]['id'];
`;
}

function generateAdminAccessGo(contract) {
	const roleConsts = contract.roles
		.map((role) => `\tRole${goIdentifier(role)} = ${JSON.stringify(role)}`)
		.join('\n');
	const adminRoleConsts = contract.adminRoles
		.map((role) => `\tAdminRole${goIdentifier(role)} = ${JSON.stringify(role)}`)
		.join('\n');
	const permissionConsts = contract.permissions
		.map((permission) => {
			const name = permission.replace(/^admin\./, '');
			return `\tPermission${goIdentifier(name)} = ${JSON.stringify(permission)}`;
		})
		.join('\n');
	const rolePermissions = Object.entries(contract.rolePermissions)
		.map(([role, permissions]) => `\t${JSON.stringify(role)}: {\n${goStringList(permissions)}\n\t},`)
		.join('\n');
	return `// Code generated by packages/config/scripts/generate-contracts.mjs; DO NOT EDIT.
package adminaccess

import "sort"

const (
${roleConsts}
)

const (
${adminRoleConsts}
)

const (
${permissionConsts}
)

var Roles = []string{
${goStringList(contract.roles)}
}

var AdminRoles = []string{
${goStringList(contract.adminRoles)}
}

var Permissions = []string{
${goStringList(contract.permissions)}
}

var RolePermissions = map[string][]string{
${rolePermissions}
}

func IsRole(value string) bool {
\treturn contains(Roles, value)
}

func IsAdminRole(value string) bool {
\treturn contains(AdminRoles, value)
}

func IsPermission(value string) bool {
\treturn contains(Permissions, value)
}

func PermissionsForRole(role string) []string {
\tpermissions := RolePermissions[role]
\treturn append([]string{}, permissions...)
}

func PermissionsForRoles(roles []string) []string {
\tgrants := map[string]bool{}
\tfor _, role := range roles {
\t\tfor _, permission := range RolePermissions[role] {
\t\t\tgrants[permission] = true
\t\t}
\t}

\tpermissions := make([]string, 0, len(grants))
\tfor permission := range grants {
\t\tpermissions = append(permissions, permission)
\t}
\tsort.Strings(permissions)

\treturn permissions
}

func contains(values []string, value string) bool {
\tfor _, candidate := range values {
\t\tif candidate == value {
\t\t\treturn true
\t\t}
\t}
\treturn false
}
`;
}

function generateProductCatalogGo(products) {
	return `// Code generated by packages/config/scripts/generate-contracts.mjs; DO NOT EDIT.
package productcatalog

const (
${products.map((product) => `\tProduct${goIdentifier(product.id)} = ${JSON.stringify(product.id)}`).join('\n')}
)

var IDs = []string{
${goStringList(products.map((product) => product.id))}
}

func IsValidID(productID string) bool {
\tfor _, id := range IDs {
\t\tif productID == id {
\t\t\treturn true
\t\t}
\t}

\treturn false
}
`;
}

const adminAccess = readJson('packages/config/admin-access.json');
const products = readJson('packages/config/products.json');

write('packages/config/admin-access.ts', generateAdminAccessTs(adminAccess));
write('packages/config/products.ts', generateProductsTs(products));
write('packages/adminaccess/adminaccess.go', gofmt(generateAdminAccessGo(adminAccess)));
write('packages/productcatalog/products.go', gofmt(generateProductCatalogGo(products)));

if (drift) {
	process.exitCode = 1;
}
